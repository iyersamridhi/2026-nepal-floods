let currentLang = localStorage.getItem("lang") || "en";

function t(key) {
  return I18N[currentLang][key] || I18N.en[key] || key;
}

function renderSiteDisclaimer() {
  // Banner + footer carry the disclaimer. Avoid a second block under every subtitle.
  document.querySelectorAll("header.site-header .site-disclaimer").forEach((el) => {
    el.remove();
  });
}

function renderVolunteerStrip() {
  document.querySelectorAll("#volunteer-strip").forEach((strip) => {
    const text = strip.querySelector("[data-i18n='volunteerStrip']");
    const cta = strip.querySelector("[data-i18n='volunteerStripCta']");
    if (text) text.textContent = t("volunteerStrip");
    if (cta) cta.textContent = t("volunteerStripCta");
  });
}

function renderSodheraBlocks() {
  document.querySelectorAll("[data-sodhera-block]").forEach((el) => {
    el.querySelectorAll("[data-i18n]").forEach((node) => {
      const key = node.getAttribute("data-i18n");
      if (key) node.textContent = t(key);
    });
  });
}

function renderFooter() {
  document.querySelectorAll(".site-footer").forEach((el) => {
    el.innerHTML = `${t("footer")} <span class="footer-sep">·</span> <a href="/legal.html" class="footer-link footer-link-prominent">${t("legalLink")}</a> <span class="footer-sep">·</span> <a href="/feedback.html" class="footer-link footer-link-prominent">${t("feedbackVolunteerLink")}</a>`;
  });
}

function renderLangBlocks() {
  document.querySelectorAll("[data-lang-block]").forEach((el) => {
    const show = el.getAttribute("data-lang-block") === currentLang;
    el.hidden = !show;
  });
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem("lang", lang);
  document.documentElement.lang = lang === "np" ? "ne" : "en";
  renderNav();
  renderSiteDisclaimer();
  renderVolunteerStrip();
  renderLangBlocks();
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
  markActiveNav();
  renderFooter();
  window.dispatchEvent(new Event("langchange"));
}

function initLang() {
  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.addEventListener("click", () => setLang(btn.dataset.lang));
  });
  setLang(currentLang);
}

