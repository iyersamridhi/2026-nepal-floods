let currentLang = localStorage.getItem("lang") || "en";

function t(key) {
  return I18N[currentLang][key] || I18N.en[key] || key;
}

function renderSiteDisclaimer() {
  document.querySelectorAll("header.site-header").forEach((header) => {
    let el = header.querySelector(".site-disclaimer");
    if (!el) {
      const sub = header.querySelector(".subtitle");
      if (!sub) return;
      el = document.createElement("p");
      el.className = "site-disclaimer";
      el.setAttribute("data-i18n", "siteDisclaimer");
      sub.after(el);
    }
    el.textContent = t("siteDisclaimer");
  });
}

function renderVolunteerStrip() {
  document.querySelectorAll("#volunteer-strip").forEach((strip) => {
    const text = strip.querySelector("[data-i18n='volunteerStrip']");
    const cta = strip.querySelector("[data-i18n='volunteerStripCta']");
    if (text) text.textContent = t("volunteerStrip");
    if (cta) cta.textContent = t("volunteerStripCta");
  });
}

function renderFooter() {
  document.querySelectorAll(".site-footer").forEach((el) => {
    el.innerHTML = `${t("footer")} <span class="footer-sep">·</span> <a href="/legal.html" class="footer-link footer-link-prominent">${t("legalLink")}</a> <span class="footer-sep">·</span> <a href="/feedback.html" class="footer-link footer-link-prominent">${t("feedbackVolunteerLink")}</a>`;
  });
}

function renderLangBlocks() {
  document.querySelectorAll("[data-lang-block]").forEach((el) => {
    const show = el.getAttribute("data-lang-block") === currentLang;
    el.hidden = !show;
  });
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem("lang", lang);
  document.documentElement.lang = lang === "np" ? "ne" : "en";
  renderNav();
  renderSiteDisclaimer();
  renderVolunteerStrip();
  renderLangBlocks();
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
  markActiveNav();
  renderFooter();
}

function initLang() {
  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.addEventListener("click", () => setLang(btn.dataset.lang));
  });
  setLang(currentLang);
}

function renderNav() {
  const el = document.getElementById("site-nav");
  if (!el) return;
  el.innerHTML = `
    <a href="/" data-page="home" data-i18n="navHome">${t("navHome")}</a>
    <a href="/wizard.html" data-page="wizard" data-i18n="navWizard">${t("navWizard")}</a>
    <a href="/search.html" data-page="search" data-i18n="navSearch">${t("navSearch")}</a>
    <a href="/report.html" data-page="report" data-i18n="navReport">${t("navReport")}</a>
    <a href="/updates.html" data-page="updates" data-i18n="navUpdates">${t("navUpdates")}</a>
    <a href="/resources.html" data-page="resources" data-i18n="navResources">${t("navResources")}</a>
    <a href="/feedback.html" data-page="feedback" class="nav-feedback" data-i18n="navFeedback">${t("navFeedback")}</a>
  `;
}

function markActiveNav() {
  const page = document.body.dataset.page;
  document.querySelectorAll(".nav-links a").forEach((a) => {
    a.classList.toggle("active", a.dataset.page === page);
  });
}

function encodeWhatsApp(phone, text) {
  const num = phone.replace(/\D/g, "");
  let msg = text || "";
  if (msg.length > 1200) {
    msg = msg.slice(0, 1150) + "\n\n[Message shortened. Full report is on your clipboard — paste after opening.]";
  }
  return `https://wa.me/${num}?text=${encodeURIComponent(msg)}`;
}

function encodeMailto(email, subject, body) {
  return `mailto:${email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
}

document.addEventListener("DOMContentLoaded", () => {
  renderNav();
  renderSiteDisclaimer();
  renderVolunteerStrip();
  renderLangBlocks();
  renderFooter();
  initLang();
  markActiveNav();
});
